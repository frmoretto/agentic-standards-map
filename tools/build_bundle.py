"""Build map-bundle.md, the whole map in one file.

Usage: python tools/build_bundle.py

The bundle opens with the README (without its navigation table and its licence and contributing sections),
then the index. Order of the parts: README, METHOD.md, notes/intro.md, notes/disclosure-short.md, the status table of the
core entries (generated), the seams (notes/seams.md), the payment protocol matrix (generated), the core
entries, the context entries, the appendices Evidence and Open proposals (generated), the full disclosure
(notes/disclosure.md) and the calendar (notes/calendar-2026.md).

Nothing in the bundle is written by hand here: every part is read from the repository or produced by
tools/build_map.py. The text added by this script is structural only (title, index, separators).
"""
from pathlib import Path
import importlib.util
import re

ROOT = Path(__file__).resolve().parent.parent

spec = importlib.util.spec_from_file_location("build_map", ROOT / "tools" / "build_map.py")
bm = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bm)

def read(rel):
    p = ROOT / rel
    if not p.exists():
        raise SystemExit(f"{rel} is missing")
    return p.read_text(encoding="utf-8").strip()


def readme_opening():
    """The README without its navigation table and its licence and contributing sections."""
    sections = re.split(r"(?m)^(?=## )", read("README.md"))
    kept = [x for x in sections if not x.startswith(("## Start here", "## Contributing", "## Licence"))]
    return "".join(kept).rstrip()


def build_bundle_md():
    entries = bm.load()
    core = sorted((e for e in entries if e["tier"] == "core"), key=bm.key)
    context = sorted((e for e in entries if e["tier"] == "context"), key=bm.key)
    parts = [
        ("readme", "README", readme_opening()),
        ("method", "Method", read("METHOD.md")),
        ("intro", "Introduction", read("notes/intro.md")),
        ("disclosure-short", "Disclosure (short)", read("notes/disclosure-short.md")),
        ("status", "Core entries: status", bm.status_table(entries)),
        ("seams", "Seams", read("notes/seams.md")),
        ("matrix", "Payment protocols compared", bm.matrix(entries)),
        ("core", "Core entries", bm.core_cards(entries)),
        ("context", "Context entries", bm.context_cards(entries)),
        ("evidence", "Appendix: Evidence and coverage", bm.evidence(entries)),
        ("proposals", "Appendix: Open proposals", bm.open_proposals(entries)),
        ("disclosure", "Appendix: Full disclosure", read("notes/disclosure.md")),
        ("calendar", "Appendix: Calendar", read("notes/calendar-2026.md")),
    ]
    out = ['<a id="part-readme"></a>', "", parts[0][2], "", "---", "",
           "Version 1.3 (2026-11-02) · site updated 2026-11-02. Generated by `tools/build_bundle.py` from the repository files. Do not edit by hand.",
           "", "## Index", ""]
    for i, (pid, title, _) in enumerate(parts, 1):
        out.append(f"{i}. [{title}](#part-{pid})")
    out += ["", f"Core entries ({len(core)}):", ""] + [f"- [{e['name']}](#{e['id']})" for e in core]
    out += ["", f"Context entries ({len(context)}):", ""] + [f"- [{e['name']}](#{e['id']})" for e in context]
    for i, (pid, title, body) in enumerate(parts[1:], 2):
        out += ["", "---", "", f'<a id="part-{pid}"></a>', f"# Part {i}: {title}", "", body]
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    bundle = build_bundle_md()
    (ROOT / "map-bundle.md").write_text(bundle, encoding="utf-8", newline="\n")
    print(f"map-bundle.md written: {len(bundle.encode('utf-8'))} bytes, {bundle.count(chr(10))} lines")


if __name__ == "__main__":
    main()
